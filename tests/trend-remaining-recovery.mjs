import assert from 'node:assert/strict';
import {getTrendOutline,IBS_AREAS} from '../functions/_lib/trend-outline.js';
import {repairTarget} from '../functions/_lib/trend-question-repair.js';
globalThis.fetch=async()=>{throw Error('Unexpected network request')};
const outline=await getTrendOutline('Final','Integrated Business Solutions (Multidisciplinary Case Study with Strategic Management)');
assert.equal(outline.chapters.length,7);
assert.equal(new Set(outline.chapters).size,7);
assert(outline.chapters.every(c=>c.startsWith('Syllabus area: ')));
assert(IBS_AREAS.includes('Corporate and Economic Laws'));
const draft={questions:Array.from({length:6},(_,i)=>({ref:String(i+1),section:'Part II',page:i+1}))};
const diagnostic={section:'Part II',maximum:70,chooseCount:4,ranges:[14,8,8,8,14,14].map((marks,i)=>({number:i+1,min:marks,max:marks,optional:i>0}))};
assert.equal(repairTarget(draft,diagnostic).number,2);
assert.equal(repairTarget(draft,diagnostic,['Part II|2']).number,3);
assert.equal(repairTarget(draft,diagnostic,['Part II|2','Part II|3']).number,4);
assert.equal(repairTarget(draft,diagnostic,['Part II|2','Part II|3','Part II|4']),null);
assert.deepEqual(diagnostic.ranges.map(r=>r.min),[14,8,8,8,14,14]);
const missingCompulsory={...diagnostic,ranges:[13,14,14,14,14,14].map((marks,i)=>({number:i+1,min:marks,max:marks,optional:i>0}))};
assert.equal(repairTarget(draft,missingCompulsory).number,1);
console.log('PASS: IBS resolves without chapter scraping; repeated wrong optional marks select the offending questions, preserving marks and compulsory-question detection.');
